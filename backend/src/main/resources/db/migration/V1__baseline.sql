-- ─────────────────────────────────────────────────────────────────
--  Bloom · baseline schema
--  Versioned with Flyway for the `prod` profile. Uses IF NOT EXISTS so
--  it is safe to apply on top of a database that Hibernate already
--  created (baseline-on-migrate handles the version stamp).
-- ─────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS habits (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    streak_count        INTEGER      NOT NULL DEFAULT 0,
    last_completed_date DATE,
    created_at          TIMESTAMP    NOT NULL,
    color_index         INTEGER      NOT NULL DEFAULT 0,
    deadline            VARCHAR(5),
    schedule_type       VARCHAR(10),
    schedule_days       VARCHAR(20),
    schedule_per_week   INTEGER,
    category            VARCHAR(40),
    archived            BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order          INTEGER      NOT NULL DEFAULT 0,
    reminder_time       VARCHAR(5)
);

CREATE TABLE IF NOT EXISTS habit_completions (
    habit_id       BIGINT NOT NULL,
    completed_date DATE   NOT NULL,
    PRIMARY KEY (habit_id, completed_date),
    CONSTRAINT fk_habit_completions_habit
        FOREIGN KEY (habit_id) REFERENCES habits (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS todos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(120) NOT NULL,
    note         VARCHAR(280),
    category     VARCHAR(20)  NOT NULL DEFAULT 'personal',
    is_done      BOOLEAN      NOT NULL DEFAULT FALSE,
    due_date     DATE,
    due_time     TIME,
    created_at   TIMESTAMP    NOT NULL,
    completed_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS app_meta (
    meta_key   VARCHAR(64) NOT NULL PRIMARY KEY,
    meta_value VARCHAR(64)
);
